import { readdirSync, existsSync, writeFileSync, mkdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const FINAL_DIR = join(ROOT, "public", "images", "final");
const PLACEHOLDER_DIR = join(ROOT, "public", "images", "placeholders");
const OUT_FILE = join(ROOT, "src", "lib", "image-manifest.generated.ts");
const REPORT_FILE = join(ROOT, "reports", "image-shot-list.md");

const EXTENSIONS = [".jpg", ".jpeg", ".png", ".webp", ".svg"];

const TOP_12 = [
  "hero.background",
  "og.default",
  "page.passports.hero",
  "page.visas.hero",
  "destination.mexico.card",
  "destination.canada.card",
  "destination.unitedKingdom.card",
  "destination.france.card",
  "destination.italy.card",
  "destination.japan.card",
  "destination.germany.card",
  "page.tools.hero",
];

function slotUsage(slotId) {
  if (slotId === "hero.background") return "Homepage hero background";
  if (slotId === "og.default") return "Default Open Graph / social share image";
  if (slotId.startsWith("page.") && slotId.endsWith(".hero")) {
    return `${slotId.replace(/^page\./, "").replace(/\.hero$/, "")} hub hero`;
  }
  if (slotId.startsWith("destination.") && slotId.endsWith(".card")) {
    return `Destination card: ${slotId.replace(/^destination\./, "").replace(/\.card$/, "")}`;
  }
  if (slotId.startsWith("destination.") && slotId.endsWith(".hero")) {
    return `Destination hero: ${slotId.replace(/^destination\./, "").replace(/\.hero$/, "")}`;
  }
  if (slotId.startsWith("immigration.")) {
    return `Immigration service panel: ${slotId.replace(/^immigration\./, "")}`;
  }
  if (slotId.startsWith("team.avatar.")) return "Team avatar";
  if (slotId.startsWith("team.member.")) return "Team member portrait";
  if (slotId.startsWith("article.")) return `Article cover: ${slotId}`;
  return slotId;
}

function placeholderSize(slotId) {
  const svg = readFileSync(join(PLACEHOLDER_DIR, `${slotId}.svg`), "utf-8");
  const width = Number(svg.match(/width="(\d+)"/)?.[1]);
  const height = Number(svg.match(/height="(\d+)"/)?.[1]);
  return { width, height };
}

function isBlocking(slotId) {
  if (slotId.startsWith("team.") || slotId.startsWith("article.")) return false;
  if (slotId.startsWith("destination.")) return false;
  if (slotId === "hero.background" || slotId === "og.default") return false;
  return true;
}

function findFinalImage(slotId) {
  if (!existsSync(FINAL_DIR)) return null;
  for (const ext of EXTENSIONS) {
    const candidate = `${slotId}${ext}`;
    if (existsSync(join(FINAL_DIR, candidate))) {
      return `/images/final/${candidate}`;
    }
  }
  return null;
}

const manifest = {};
const slotIds = [];

if (existsSync(PLACEHOLDER_DIR)) {
  const placeholderFiles = readdirSync(PLACEHOLDER_DIR);
  for (const file of placeholderFiles) {
    if (!file.endsWith(".svg")) continue;
    const slotId = file.replace(/\.svg$/, "");
    const finalSrc = findFinalImage(slotId);
    manifest[slotId] = finalSrc || `/images/placeholders/${file}`;
    slotIds.push(slotId);
  }
}

const content = `// Auto-generated by scripts/build-image-manifest.mjs. Do not edit manually.
export const IMAGE_MANIFEST: Record<string, string> = ${JSON.stringify(manifest, null, 2)};
`;

writeFileSync(OUT_FILE, content, "utf-8");

const blocking = slotIds.filter(isBlocking);
const missing = slotIds.filter((slotId) => !findFinalImage(slotId));
const missingBlocking = missing.filter(isBlocking);
const prioritized = [
  ...TOP_12.filter((slotId) => slotIds.includes(slotId)),
  ...missingBlocking.filter((slotId) => !TOP_12.includes(slotId)).sort(),
  ...missing.filter((slotId) => !isBlocking(slotId)).sort(),
];

const rows = prioritized.map((slotId, index) => {
  const { width, height } = placeholderSize(slotId);
  const aspect = (width / height).toFixed(2);
  const priority = index < TOP_12.length ? `Top ${index + 1}` : isBlocking(slotId) ? "Blocking" : "Optional";
  return `| ${priority} | \`${slotId}\` | ${width}×${height} (${aspect}:1) | ${slotUsage(slotId)} | \`public/images/final/${slotId}.jpg\` |`;
}).join("\n");

const report = `# Image shot list

Generated by \`npm run images:manifest\`. Roadmap item A8 / owner gates B-8, B-13.

- Total slots: **${slotIds.length}**
- Launch-blocking slots: **${blocking.length}**
- Still on placeholders: **${missing.length}** (${missingBlocking.length} blocking)

To replace an image, drop the final file at the path in the last column, then run
\`npm run images:manifest\`. No component changes are needed. Use .jpg, .jpeg,
.png or .webp; the manifest prefers the final file over the placeholder.

## Top 12 owner shots

Shoot or license these first, in this order. They cover the homepage, social
sharing and the two highest-traffic hubs.

| Priority | Slot | Size (px) | Usage | Deliverable |
| --- | --- | --- | --- | --- |
${rows.split("\n").slice(0, TOP_12.length).join("\n")}

## Remaining slots

| Priority | Slot | Size (px) | Usage | Deliverable |
| --- | --- | --- | --- | --- |
${rows.split("\n").slice(TOP_12.length).join("\n") || "| — | None | — | — | — |"}
`;

mkdirSync(join(ROOT, "reports"), { recursive: true });
writeFileSync(REPORT_FILE, report, "utf-8");
console.log(
  `Wrote ${slotIds.length} image slot entries to src/lib/image-manifest.generated.ts (${blocking.length} blocking, ${missing.length} placeholders)`,
);
console.log("Wrote reports/image-shot-list.md");
