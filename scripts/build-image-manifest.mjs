import { readdirSync, existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const FINAL_DIR = join(ROOT, "public", "images", "final");
const PLACEHOLDER_DIR = join(ROOT, "public", "images", "placeholders");
const OUT_FILE = join(ROOT, "src", "lib", "image-manifest.generated.ts");

const EXTENSIONS = [".jpg", ".jpeg", ".png", ".webp", ".svg"];

function findFinalImage(slotId) {
  if (!existsSync(FINAL_DIR)) return null;
  for (const ext of EXTENSIONS) {
    const candidate = `${slotId}${ext}`;
    if (existsSync(join(FINAL_DIR, candidate))) {
      return `/images/final/${candidate}`;
    }
  }
  return null;
}

const manifest = {};

if (existsSync(PLACEHOLDER_DIR)) {
  const placeholderFiles = readdirSync(PLACEHOLDER_DIR);
  for (const file of placeholderFiles) {
    if (!file.endsWith(".svg")) continue;
    const slotId = file.replace(/\.svg$/, "");
    const finalSrc = findFinalImage(slotId);
    manifest[slotId] = finalSrc || `/images/placeholders/${file}`;
  }
}

const content = `// Auto-generated by scripts/build-image-manifest.mjs. Do not edit manually.
export const IMAGE_MANIFEST: Record<string, string> = ${JSON.stringify(manifest, null, 2)};
`;

writeFileSync(OUT_FILE, content, "utf-8");
console.log(`Wrote ${Object.keys(manifest).length} image slot entries to src/lib/image-manifest.generated.ts`);
