/**
 * Image slot registry (roadmap section 7).
 *
 * Every place that needs a photo works today with a marked placeholder;
 * replacing it needs no code change — drop the real file at
 * public/images/final/{slot}.jpg and it is preferred automatically.
 *
 * Slots are intentional: no slot ships without an explicit width/height so
 * placeholders (and eventual finals) never collapse into empty gray boxes.
 */

import { DESTINATIONS } from "./destinations";
import { IMMIGRATION_SERVICES } from "./immigration-programs";
import { IMAGE_MANIFEST } from "./image-manifest.generated";

export type ImageSlot =
  | "hero.background"
  | "og.default"
  | "page.passports.hero"
  | "page.visas.hero"
  | "page.immigration.hero"
  | "page.tools.hero"
  | "page.resources.hero"
  | "page.about.hero"
  | "page.contact.hero"
  | "page.insights.hero"
  | `destination.${string}.card`
  | `destination.${string}.hero`
  | `immigration.${string}`
  | `article.${string}.cover`
  | "team.avatar.1"
  | "team.avatar.2"
  | "team.avatar.3"
  | "team.avatar.4"
  | "team.member.01"
  | "team.member.02"
  | "team.member.03"
  | "team.member.04"
  | "team.member.05"
  | "team.member.06";

export interface ImageSlotDef {
  id: ImageSlot;
  width: number;
  height: number;
  usage: string;
  /** When true, launch-check treats an unresolved placeholder as blocking. */
  launchBlocking: boolean;
}

function pageHeroSlots(): ImageSlotDef[] {
  return [
    "passports",
    "visas",
    "immigration",
    "tools",
    "resources",
    "about",
    "contact",
    "insights",
  ].map((route) => ({
    id: `page.${route}.hero` as ImageSlot,
    width: 2400,
    height: 900,
    usage: `${route} hub hero`,
    launchBlocking: true,
  }));
}

function destinationSlots(): ImageSlotDef[] {
  const slots: ImageSlotDef[] = [];
  for (const destination of DESTINATIONS) {
    slots.push(
      {
        id: `destination.${destination.key}.card` as ImageSlot,
        width: 1200,
        height: 1600,
        usage: `Destination card: ${destination.key}`,
        launchBlocking: true,
      },
      {
        id: `destination.${destination.key}.hero` as ImageSlot,
        width: 2400,
        height: 1000,
        usage: `Destination hero: ${destination.key}`,
        launchBlocking: true,
      }
    );
  }
  return slots;
}

function immigrationSlots(): ImageSlotDef[] {
  return IMMIGRATION_SERVICES.map((service) => ({
    id: `immigration.${service.key}` as ImageSlot,
    width: 1200,
    height: 1600,
    usage: `Immigration panel: ${service.key}`,
    launchBlocking: true,
  }));
}

export const IMAGE_SLOTS: ImageSlotDef[] = [
  { id: "hero.background", width: 2400, height: 1350, usage: "Homepage background", launchBlocking: true },
  { id: "og.default", width: 1200, height: 630, usage: "Default Open Graph image", launchBlocking: true },
  ...pageHeroSlots(),
  ...destinationSlots(),
  ...immigrationSlots(),
  { id: "team.avatar.1", width: 160, height: 160, usage: "Team avatar", launchBlocking: false },
  { id: "team.avatar.2", width: 160, height: 160, usage: "Team avatar", launchBlocking: false },
  { id: "team.avatar.3", width: 160, height: 160, usage: "Team avatar", launchBlocking: false },
  { id: "team.avatar.4", width: 160, height: 160, usage: "Team avatar", launchBlocking: false },
  { id: "team.member.01", width: 800, height: 1000, usage: "Team member 01", launchBlocking: false },
  { id: "team.member.02", width: 800, height: 1000, usage: "Team member 02", launchBlocking: false },
  { id: "team.member.03", width: 800, height: 1000, usage: "Team member 03", launchBlocking: false },
  { id: "team.member.04", width: 800, height: 1000, usage: "Team member 04", launchBlocking: false },
  { id: "team.member.05", width: 800, height: 1000, usage: "Team member 05", launchBlocking: false },
  { id: "team.member.06", width: 800, height: 1000, usage: "Team member 06", launchBlocking: false },
];

export function slotDef(slot: ImageSlot): ImageSlotDef {
  const def = IMAGE_SLOTS.find((s) => s.id === slot);
  if (def) return def;
  if (slot.startsWith("article.") && slot.endsWith(".cover")) {
    return {
      id: slot,
      width: 1600,
      height: 900,
      usage: `Article cover: ${slot}`,
      launchBlocking: true,
    };
  }
  throw new Error(`Unknown image slot: ${slot}`);
}

/**
 * Resolve a slot to an image source with explicit dimensions.
 * Prefers public/images/final/{slot}.jpg, falls back to
 * public/images/placeholders/{slot}.jpg (generated by
 * scripts/generate-placeholders.mjs). Never returns undefined.
 */
export function getImage(slot: ImageSlot): { src: string; width: number; height: number } {
  const { width, height } = slotDef(slot);
  const src = IMAGE_MANIFEST[slot] ?? `/images/placeholders/${slot}.svg`;
  return {
    src,
    width,
    height,
  };
}

export function isLaunchBlocking(slot: ImageSlot): boolean {
  return slotDef(slot).launchBlocking;
}

